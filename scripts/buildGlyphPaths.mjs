/**
 * Build script: extracts SVG path data from Bravura.otf for SMuFL glyphs
 * and generates src/render/glyphPaths.generated.ts.
 *
 * Run with: node scripts/buildGlyphPaths.mjs
 */

import fs from 'fs';
import path from 'path';
import opentype from 'opentype.js';

const rootDir = process.cwd();
const otfPath = path.join(rootDir, 'scripts', 'assets', 'Bravura.otf');
const glyphnamesPath = path.join(rootDir, 'public', 'fonts', 'glyphnames.json');
const outputPath = path.join(rootDir, 'src', 'render', 'glyphPaths.generated.ts');

if (!fs.existsSync(otfPath)) {
  console.error(`Error: Bravura.otf not found at ${otfPath}`);
  process.exit(1);
}

const glyphnames = JSON.parse(fs.readFileSync(glyphnamesPath, 'utf8'));
const otfBuffer = fs.readFileSync(otfPath);
const arrayBuffer = otfBuffer.buffer.slice(otfBuffer.byteOffset, otfBuffer.byteOffset + otfBuffer.byteLength);
const font = opentype.parse(arrayBuffer);

console.log(`Bravura loaded: unitsPerEm = ${font.unitsPerEm}, total font glyphs = ${font.glyphs.length}`);

// Category regex matching all notation symbols used in ScoreForge and standard SMuFL
const matchRegex = /^(gClef|fClef|cClef|notehead|rest|flag|accidental|timeSig|augmentationDot|artic|fermata|dynamic|repeat|segno|coda|caesura|breathMark|stem|ledgerLine)/i;

const glyphPaths = {};
let count = 0;

for (const [name, entry] of Object.entries(glyphnames)) {
  if (matchRegex.test(name)) {
    const code = parseInt(entry.codepoint.replace('U+', ''), 16);
    const glyph = font.charToGlyph(String.fromCodePoint(code));
    if (glyph && glyph.unicode !== undefined) {
      const p = glyph.getPath(0, 0, font.unitsPerEm);
      const d = p.toPathData(1); // 1 decimal place precision
      if (d && d.length > 0) {
        glyphPaths[name] = d;
        count++;
      }
    }
  }
}

console.log(`Extracted ${count} glyph paths.`);

const fileContent = `/**
 * Auto-generated SVG glyph paths extracted from Bravura.otf via opentype.js.
 * Generated by scripts/buildGlyphPaths.mjs.
 * DO NOT EDIT DIRECTLY.
 */

export const UNITS_PER_EM = ${font.unitsPerEm};

export const GLYPH_PATHS: Record<string, string> = ${JSON.stringify(glyphPaths, null, 2)};

/**
 * Returns the SVG path data string in font units for the given SMuFL glyph name.
 */
export function getGlyphPath(name: string): string | undefined {
  return GLYPH_PATHS[name];
}
`;

fs.writeFileSync(outputPath, fileContent, 'utf8');
console.log(`Wrote ${outputPath} successfully (${(fileContent.length / 1024).toFixed(1)} KB).`);
